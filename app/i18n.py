from __future__ import annotations

from datetime import date, datetime

from fastapi import Request

DEFAULT_LANGUAGE = "en"
SUPPORTED_LANGUAGES = ("de", "en")
LANGUAGE_LABELS = {
    "de": "Deutsch",
    "en": "English",
}


def normalize_language(value: str | None, default: str = DEFAULT_LANGUAGE) -> str:
    if value:
        language = value.strip().lower().replace("_", "-").split("-", 1)[0]
        if language in SUPPORTED_LANGUAGES:
            return language
    if default == "":
        return ""
    return default if default in SUPPORTED_LANGUAGES else DEFAULT_LANGUAGE


def browser_language(request: Request, default: str = DEFAULT_LANGUAGE, *, allow_query: bool = False) -> str:
    if allow_query and request.query_params.get("lang"):
        return normalize_language(request.query_params["lang"], default)
    weighted: list[tuple[float, int, str]] = []
    for position, item in enumerate(request.headers.get("accept-language", "").split(",")):
        parts = item.strip().split(";")
        language = parts[0].strip()
        quality = 1.0
        for parameter in parts[1:]:
            if parameter.strip().startswith("q="):
                try:
                    quality = float(parameter.strip()[2:])
                except ValueError:
                    quality = 0.0
        normalized = normalize_language(language, "")
        if normalized in SUPPORTED_LANGUAGES and quality > 0:
            weighted.append((quality, -position, normalized))
    return max(weighted)[2] if weighted else normalize_language(default)


def translate(language: str, key: str, **values: object) -> str:
    language = normalize_language(language)
    text = TRANSLATIONS.get(language, {}).get(key) or TRANSLATIONS[DEFAULT_LANGUAGE].get(key) or key
    return text.format(**values)


def email_body(language: str, key: str, **values: object) -> str:
    return (
        f"{translate(language, key, **values)}\n\n---\n"
        f"{translate(language, 'email.automatic_notice')}"
    )


def format_datetime(value: datetime | None, language: str) -> str:
    if value is None:
        return ""
    if normalize_language(language) == "de":
        return value.strftime("%d.%m.%Y, %H:%M")
    return value.strftime("%Y-%m-%d %H:%M")


def format_date(value: date | datetime, language: str) -> str:
    actual = value.date() if isinstance(value, datetime) else value
    if normalize_language(language) == "de":
        return actual.strftime("%d.%m.%Y")
    return actual.isoformat()


